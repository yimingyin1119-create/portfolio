const topo = JSON.parse(readFileSync(new URL('./node_modules/world-atlas/countries-110m.json', import.meta.url)));
const all = feature(topo, topo.objects.countries);
const land = { type: 'FeatureCollection', features: all.features.filter(f => f.properties.name !== 'Antarctica') };
const projection = geoNaturalEarth1().fitExtent([[8, 8], [W - 8, H - 8]], land);
const LAND = geoPath(projection).digits(1)(land);

const round = n => Math.round(n * 10) / 10;
const POINTS = {};
for (const c of COUNTRIES) {
  for (const city of c.cities) {
    if (!CITY[city]) throw new Error(`no coordinates for ${city}`);
    const [x, y] = projection(CITY[city]);
    POINTS[city] = [round(x), round(y)];
  }
}

// Fly-to target per country: the centre of its cities, zoomed so they fit with some margin.
const FOCUS = {};
for (const c of COUNTRIES) {
  const pts = c.cities.map(city => POINTS[city]);
  const xs = pts.map(p => p[0]), ys = pts.map(p => p[1]);
  const [x0, x1, y0, y1] = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)];
  const scale = Math.min(6, Math.max(1.6, Math.min(W / (x1 - x0 + 160), H / (y1 - y0 + 120))));
  FOCUS[c.id] = { x: round((x0 + x1) / 2), y: round((y0 + y1) / 2), scale: round(scale) };
}

mkdirSync(new URL('../assets/map/', import.meta.url), { recursive: true });
const out = `// Generated by tools/build-map.mjs from Natural Earth 110m (world-atlas, ISC). Do not edit by hand.
export const VIEW = { width: ${W}, height: ${H} };
export const LAND = ${JSON.stringify(LAND)};
export const POINTS = ${JSON.stringify(POINTS)};
export const FOCUS = ${JSON.stringify(FOCUS)};
`;
writeFileSync(new URL('../assets/map/world.js', import.meta.url), out);
console.log(`world.js ${(out.length / 1024).toFixed(1)} KB, ${Object.keys(POINTS).length} cities`);
